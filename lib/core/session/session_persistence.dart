/// 會話秘密的持久化協定：把「原生端把秘密放哪」这件事抽象成協定，實作在 `lib/platform/`。
///
/// 這層抽象存在的理由有三：
/// 1. 核心不依賴任何儲存套件（與介面語言、位址設定同一取向），控制器可直接以
///    記憶體替身做測試，包括「寫入失敗」「讀取失敗」這類真機上難以穩定重現的路徑。
/// 2. 秘密的保存範圍以「正規化後的伺服器身份」為鍵：一台伺服器一枚秘密，彼此隔離，
///    從協定層就排除「所有伺服器共用一枚」或「按登入名存」這類會串台的鍵法。
/// 3. 失敗必須如實上拋：實作不得在安全儲存不可用时降級成明文落盤，也不得吞掉錯誤
///    回一個假的成功——那會把「沒存住」偽裝成「已登出」。
library;

/// 以伺服器身份為鍵存取會話秘密的協定。
abstract interface class SessionPersistence {
  /// 讀取指定伺服器身份對應的會話秘密；未保存過時回傳 `null`。
  ///
  /// 讀取失敗（例如 Linux 沒有可用的鑰匙圈服務）一律上拋例外，不回 `null`——
  /// `null` 的語意是「這台沒有已登入的會話」，把「查不到」說成「沒有」會讓控制器
  /// 無緣無故把一個本來有效的會話當成正未登入。
  Future<String?> readSecret(String serverIdentity);

  /// 寫入指定伺服器身份的會話秘密。
  ///
  /// 實作只能把它交給系統級安全儲存；寫入失敗時上拋例外，絕不回退成明文儲存。
  Future<void> writeSecret(String serverIdentity, String secret);

  /// 移除指定伺服器身份的會話秘密；該身份本就沒有秘密時視為成功（不拋錯）。
  Future<void> clearSecret(String serverIdentity);
}

/// 會話狀態的統一表示：全應用只有這一組值描述「現在到底是什麼身分」。
///
/// 之所以要把狀態收斂成一個枚舉，是為了兌現「頁面不各寫一套會話邏輯」：
/// 未登入、正在驗證、已登入、已失效是四件必须互斥、且只能由會話層宣告的事。
/// 頁面若各自用「有沒有拿到使用者」「請求有沒有 401」拼湊這些判斷，就會出現
/// 同一刻兩個畫面各說各話。這裡的值與後端的會話語意一一對應，但不含任何
/// 後端沒有的狀態——能力未落地時不假裝可用。
library;

/// 目前客戶端對「這台伺服器上的我」的認知。
enum SessionStatus {
  /// 尚無依據可下結論：可能是剛啟動還沒驗證，也可能是驗證請求連不上、逾時或
  /// 本機安全儲存讀取失敗。此時既不能說未登入，也不能說已登入——把「查不了」
  /// 報成「沒登入」會無緣無故把人踢出，是比顯示不確定更糟的錯法。
  unknown,

  /// 明確未登入：沒有任何本機憑據，或伺服器已判定當前憑據不存在（機器碼 2002）。
  signedOut,

  /// 正在向伺服器確認當前提（呼叫 `/auth/session` 或提交登入的過程中）。
  ///
  /// 這是有意的过渡值：驗證中不能沿用上一份主體資料，也不能顯示「已登入」，
  /// 否則換伺服器或重新登入的瞬間會短暫顯示舊身分。
  verifying,

  /// 已登入：伺服器已確認一枚有效會話，且（原生端）對應的秘密可用。
  signedIn,

  /// 已失效：帶著憑據去問，伺服器以 2003 判定該會話已過期、被撤銷或主體狀態
  /// 變化。與 [signedOut] 的區別是「曾經登入過但已不再有效」，處置是重新登入，
  /// 而不是什麼都不用做。
  expired,
}
